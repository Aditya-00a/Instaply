def _load_bulk_slugs(filename: str) -> list[str]:
    """Load company slugs from a JSON array file in data/company_pools/."""
    path = ROOT / "data" / "company_pools" / filename
    if path.exists():
        try:
            import json as _json
            slugs = _json.loads(path.read_text(encoding="utf-8"))
            if isinstance(slugs, list):
                return [str(s).strip() for s in slugs if s]
        except Exception as exc:
            print(f"Warning: could not load {path}: {exc}")
    return []


