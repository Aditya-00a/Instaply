# ── Single-instance lockfile (Windows-compatible) ────────────────────
LOCKFILE = ROOT / "artifacts" / ".auto_apply.lock"


def _is_pid_alive(pid: int) -> bool:
    """Check if a process is still running (works on Windows + Unix)."""
    try:
        os.kill(pid, 0)
        return True
    except (OSError, ProcessLookupError):
        return False


# Global handle kept open for the lifetime of the process — this IS the lock.
_LOCK_FH = None


def _kill_old_runners():
    """Kill any existing run_auto_apply.py processes besides ourselves.

    Reads PID from lockfile and kills that specific process.
    Safe — never uses WMIC pattern matching that could match ourselves.
    """
    my_pid = os.getpid()
    if LOCKFILE.exists():
        try:
            old_pid = int(LOCKFILE.read_text().strip())
            if old_pid != my_pid and _is_pid_alive(old_pid):
                try:
                    os.kill(old_pid, 9)
                    print(f"Killed old runner PID {old_pid}")
                except Exception:
                    pass
        except (ValueError, OSError):
            pass


def _acquire_lock():
    """Ensure only one runner is active using a Windows file lock.

    Opens the lockfile with exclusive access and keeps the handle open.
    If another process holds the lock, we kill old runners and retry once.
    """
    global _LOCK_FH
    import time

    # First, kill any old runners unconditionally
    _kill_old_runners()
    time.sleep(2)  # Let OS clean up

    # Remove stale lockfile if PID inside is dead
    if LOCKFILE.exists():
        try:
            old_pid = int(LOCKFILE.read_text().strip())
            if not _is_pid_alive(old_pid):
                LOCKFILE.unlink(missing_ok=True)
        except PermissionError:
            # File handle still open from dead process — force delete via OS
            import subprocess
            subprocess.run(
                ["powershell", "-Command", f"Remove-Item -Force '{LOCKFILE}' -ErrorAction SilentlyContinue"],
                capture_output=True, timeout=5,
            )
            time.sleep(1)
        except Exception:
            try:
                LOCKFILE.unlink(missing_ok=True)
            except Exception:
                import subprocess
                subprocess.run(
                    ["powershell", "-Command", f"Remove-Item -Force '{LOCKFILE}' -ErrorAction SilentlyContinue"],
                    capture_output=True, timeout=5,
                )
                time.sleep(1)

    # Write our PID. On Windows this can fail early if another process has
    # already locked the file, so handle that path gracefully.
    try:
        LOCKFILE.write_text(str(os.getpid()))
    except PermissionError:
        print("ERROR: Could not update lockfile - another runner may be active. Exiting.")
        sys.exit(0)

    # On Windows, use msvcrt file locking for true mutual exclusion
    if sys.platform == "win32":
        import msvcrt
        try:
            _LOCK_FH = open(LOCKFILE, "r+")
            msvcrt.locking(_LOCK_FH.fileno(), msvcrt.LK_NBLCK, 1)
        except (IOError, OSError):
            print("ERROR: Could not acquire file lock — another runner may be active. Exiting.")
            sys.exit(0)
    else:
        # Unix: use fcntl
        import fcntl
        _LOCK_FH = open(LOCKFILE, "r+")
        try:
            fcntl.flock(_LOCK_FH.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except (IOError, OSError):
            print("ERROR: Could not acquire file lock — another runner may be active. Exiting.")
            sys.exit(0)


def _release_lock():
    """Remove lockfile on exit."""
    global _LOCK_FH
    try:
        if _LOCK_FH:
            _LOCK_FH.close()
            _LOCK_FH = None
        if LOCKFILE.exists() and LOCKFILE.read_text().strip() == str(os.getpid()):
            LOCKFILE.unlink()
    except Exception:
        pass


atexit.register(_release_lock)

