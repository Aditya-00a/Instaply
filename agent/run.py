# and deduplicates with the curated hardcoded lists above.
def _merge_pool(hardcoded: list[str], bulk: list[str]) -> list[str]:
    """Merge bulk slugs into hardcoded list, deduplicating case-insensitively."""
    seen = {s.lower() for s in hardcoded}
    merged = list(hardcoded)
    for slug in bulk:
        key = slug.lower()
        if key not in seen:
            seen.add(key)
            merged.append(slug)
    return merged

